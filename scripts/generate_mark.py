#!/usr/bin/env python3
"""Draw Utter's mark — the source art both icon generators consume.

Writes `Assets/AppIconSource.png`: a **white mark on black**, which is the format
`generate_icon.py` and `generate_menubar_icon.py` both expect. Each thresholds this at
luminance 96 and uses the result as an alpha mask, so only the *shape* here matters —
the black ground never reaches either output.

Why this script exists at all
-----------------------------
Two reasons, and the second is the one that will outlive the first.

**The mark had to change.** It was a lightbulb with a waveform knocked out of its
interior, drawn when the app was called *Lumen* — a name about light. The app is now
*Utter*, a name about speech, and a lightbulb says nothing about it. What survives is the
waveform, which was always the half of that mark carrying the meaning, and which matches
the app's existing visual language: the pill's level meter is the same shape, driven by
real microphone RMS.

**`AppIconSource.png` was the only asset in this repository with no stated provenance.**
Every other piece of art is either generated by a script here (`tools/newcat/` for the
pixel companions) or documented as to where it came from. A hand-supplied PNG of unknown
origin is exactly the thing that becomes a licensing question the week before someone
publishes. Drawing it from primitives makes this file its provenance: there is nothing to
attribute, because there is nothing here but rectangles.

The shape, and why it is exactly three bars
------------------------------------------
A traced audio waveform looks better at 1024px and turns to mush at 16, which is a size
this icon genuinely has to work at — Finder list and column views, the Spotlight result,
the ⌘-Tab switcher. Discrete bars degrade gracefully: they lose detail without losing
identity, because each bar is a solid block rather than a thin stroke.

**Three, because five was measured and failed.** The first version of this was five bars
(0.40, 0.72, 1.00, 0.72, 0.40). At 32px it was excellent — five clean columns,
`##..##..##..##..##`. At 16px it collapsed into a featureless rhombus with not one pixel
reaching white:

    ..++++++++++..        five bars, 16px rep — no bars, no identity
    ..++++++++++..

The arithmetic says why, and it is not a gap that can be tuned. A 16px icon is a 12.9px
plate carrying the mark at `SMALL_GLYPH_PLATE_FRACTION`, so the mark is ~8.6px wide. Five
bars plus four gaps in 8.6px is 1.7px per bar — below the point where any resampling
filter can keep a 1px gap open. Widening `GAP_RATIO` only makes the bars thinner. Three
bars in the same 8.6px is ~2.6px each and survives:

    ..+#+.##.+#+..        three bars, 16px rep — three cores, clearly separate
    ..+#+.##.+#+..

Do not "improve" this back to five without regenerating and reading the 16px rep. It is
the one size where this decision is visible, and it is not visible at any other.

Symmetric heights on purpose. An asymmetric set reads as a *specific* captured waveform,
which invites the question "of what?"; a symmetric pulse reads as a level meter, i.e. the
generic act of speaking. It also survives being mirrored in a right-to-left layout.

Three is also the fewest that still reads as a meter. Two equal bars is the universal
pause glyph; three with a tall centre cannot be mistaken for it.

No enclosed holes, deliberately. `generate_icon.py` carries a whole second code path
(`fill_enclosed_holes`) that exists because the old bulb had the waveform cut *out* of it,
so at 16px the interior collapsed and the mark read as a donut. Bars have no interior, so
that path is now a no-op on this art. It is left in place rather than deleted: it is
correct, cheap, and the next mark may need it.
"""

import os

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "Assets", "AppIconSource.png")

# Drawn far larger than any consumer needs, then left for them to downscale. Both scripts
# resample from this master rather than chaining, so headroom here costs one file on disk
# and buys clean edges at every rep.
CANVAS = 1024

# Supersample the drawing, then box-filter down. `rounded_rectangle` antialiases poorly on
# its own; a box filter on a 4x mask is an exact area average, which is what gives the bar
# caps a clean edge instead of a stair.
SUPERSAMPLE = 4

# Bar heights as a fraction of the tallest, left to right. Symmetric — see the docstring.
BAR_HEIGHTS = (0.55, 1.00, 0.55)

# Gap between bars, as a fraction of one bar's width. At three bars this is comfortable at
# every rep; it was not the binding constraint — bar *count* was. See the docstring.
GAP_RATIO = 0.62

# Fraction of the canvas the mark spans on its longest axis. The consumers crop to the
# mark's bounding box and rescale, so this only sets the drawing's own resolution, not how
# large the mark appears in either icon.
EXTENT = 0.86


def draw_mark(side):
    """The mark as an 'L' mask: white where there is ink."""
    ss = side * SUPERSAMPLE
    mask = Image.new("L", (ss, ss), 0)
    draw = ImageDraw.Draw(mask)

    count = len(BAR_HEIGHTS)
    # Solve bar width from the total span: count bars plus (count - 1) gaps.
    span = ss * EXTENT
    bar_w = span / (count + (count - 1) * GAP_RATIO)
    gap = bar_w * GAP_RATIO
    tallest = span

    # Centre the whole group on the canvas, and centre each bar vertically on the same
    # midline. A shared midline is what makes this read as a level meter; bars standing on
    # a common baseline read as a bar chart.
    x0 = (ss - span) / 2
    mid = ss / 2
    radius = bar_w / 2

    for i, h in enumerate(BAR_HEIGHTS):
        left = x0 + i * (bar_w + gap)
        height = tallest * h
        draw.rounded_rectangle(
            [left, mid - height / 2, left + bar_w, mid + height / 2],
            radius=radius,
            fill=255,
        )

    return mask.resize((side, side), Image.BOX)


def main():
    mask = draw_mark(CANVAS)

    # White mark on black, RGB — the format both consumers threshold. Not RGBA: they read
    # luminance, and an alpha channel here would be ignored and only invite confusion
    # about which channel is authoritative.
    out = Image.new("RGB", (CANVAS, CANVAS), (0, 0, 0))
    out.paste((255, 255, 255), (0, 0), mask)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    out.save(OUT)

    # Report the two numbers that decide whether the small reps work, so a change to
    # GAP_RATIO or BAR_HEIGHTS shows its effect without opening an image viewer.
    # `histogram()` rather than `getdata()`: same count, and `getdata` is deprecated
    # for removal in Pillow 14 while `histogram` is not.
    ink = sum(mask.histogram()[96:])
    bbox = mask.point(lambda v: 255 if v >= 96 else 0).getbbox()
    w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
    print(f"✓ Mark written to Assets/AppIconSource.png ({CANVAS}x{CANVAS})")
    print(f"   ink coverage {100 * ink / (CANVAS * CANVAS):.1f}%  "
          f"mark bbox {w}x{h} (aspect {w / h:.2f})")
    # The 16px rep is where bar count is decided, so report the per-bar width there rather
    # than a gap fraction — the gap was never the binding constraint. ~8.6px is the mark's
    # width inside a 16px icon; below ~2px per bar the rep collapses to a blob.
    n = len(BAR_HEIGHTS)
    bar_at_16 = 8.6 / (n + (n - 1) * GAP_RATIO)
    verdict = "ok" if bar_at_16 >= 2.0 else "TOO THIN — will blob at 16px"
    print(f"   {n} bars -> {bar_at_16:.2f}px per bar in a 16px icon ({verdict})")


if __name__ == "__main__":
    main()
